"""Browser integration checks against the running local services."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
env = dict(line.split('=', 1) for line in (ROOT / '.env').read_text(encoding='utf-8').splitlines() if '=' in line and not line.startswith('#'))
output = ROOT / 'data' / 'verification'
output.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width': 1440, 'height': 1050}, device_scale_factor=1)
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:5173')
    page.wait_for_load_state('networkidle')
    page.get_by_placeholder('请输入密码').fill(env['ADMIN_PASSWORD'])
    page.get_by_role('button', name='进入工作台').click()
    expect(page.get_by_role('heading', name='工单中心', exact=True)).to_be_visible()
    expect(page.locator('.table-footer').get_by_text('条工单', exact=False)).to_be_visible()
    page.screenshot(path=str(output / 'tickets.png'), full_page=False)
    page.get_by_role('button', name='新建工单', exact=True).click()
    page.get_by_placeholder('例如：订单未发货，申请退款').fill('浏览器联调：退款咨询')
    page.get_by_placeholder('例如 C001', exact=True).fill('C002')
    page.get_by_placeholder('例如 TF20260001，须与客户匹配').fill('TF20260002')
    page.get_by_placeholder('输入客户的完整咨询内容').fill('订单还没发货，可以申请退款吗？手机号13812345678。')
    page.get_by_role('button', name='创建工单', exact=True).click()
    expect(page.get_by_role('heading', name='浏览器联调：退款咨询')).to_be_visible()
    expect(page.get_by_text('[手机已隐藏]', exact=False)).to_be_visible()
    page.get_by_role('button', name='运行智能处理', exact=True).click()
    expect(page.get_by_text('未配置 LLM_API_KEY', exact=False)).to_be_visible(timeout=180000)
    expect(page.get_by_role('heading', name='知识检索证据', exact=False)).to_be_visible()
    page.screenshot(path=str(output / 'ticket-detail.png'), full_page=True)
    page.get_by_role('button', name='关闭此对话框').click()
    page.get_by_role('link', name='知识库管理').click()
    expect(page.get_by_role('heading', name='知识库管理', exact=True)).to_be_visible()
    page.get_by_role('button', name='测试混合检索', exact=True).click()
    expect(page.get_by_text('命中', exact=True)).to_be_visible(timeout=180000)
    expect(page.get_by_text('未发货退款', exact=False).first).to_be_visible()
    page.screenshot(path=str(output / 'knowledge.png'), full_page=True)
    page.get_by_role('link', name='流程配置').click()
    expect(page.get_by_text('电商客服处理流程', exact=True)).to_be_visible()
    page.screenshot(path=str(output / 'workflow.png'), full_page=True)
    page.get_by_role('link', name='运行日志').click()
    expect(page.get_by_role('heading', name='运行日志', exact=True)).to_be_visible()
    expect(page.get_by_text('客户意图分布', exact=True)).to_be_visible()
    page.screenshot(path=str(output / 'logs.png'), full_page=True)
    page.get_by_role('link', name='模拟订单').click()
    expect(page.get_by_text('TF20260001', exact=True)).to_be_visible()
    page.set_viewport_size({'width': 390, 'height': 844})
    page.goto('http://127.0.0.1:5173/#/tickets')
    page.wait_for_load_state('networkidle')
    page.screenshot(path=str(output / 'mobile.png'), full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 2'), 'Mobile viewport has page-level overflow'
    knowledge_page = browser.new_page(viewport={'width': 1280, 'height': 900})
    knowledge_page.goto('http://127.0.0.1:5173')
    knowledge_page.get_by_placeholder('请输入账号').fill('knowledge')
    knowledge_page.get_by_placeholder('请输入密码').fill(env['ADMIN_PASSWORD'])
    knowledge_page.get_by_role('button', name='进入工作台').click()
    expect(knowledge_page.get_by_role('heading', name='知识库管理', exact=True)).to_be_visible()
    expect(knowledge_page.get_by_role('link', name='运行日志', exact=True)).to_have_count(0)
    assert not errors, errors
    print('PASS: login, ticket creation/redaction, real RAG + explicit missing-key failure, retrieval, workflow, logs, orders, mobile, no JS errors.')
    browser.close()
